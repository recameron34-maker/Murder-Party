// Tiny auto-escaping HTML templating. Interpolated values are escaped unless
// wrapped in raw() (used only for our own rendered Markdown) or are nested
// html`` results. Arrays are joined.
const RAW = Symbol('raw');

export function raw(str) {
  return { [RAW]: String(str ?? '') };
}

export function escapeHtml(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function render(value) {
  if (value == null || value === false) return '';
  if (Array.isArray(value)) return value.map(render).join('');
  if (typeof value === 'object' && RAW in value) return value[RAW];
  return escapeHtml(value);
}

export function html(strings, ...values) {
  let out = strings[0];
  for (let i = 0; i < values.length; i++) out += render(values[i]) + strings[i + 1];
  return raw(out);
}

export function toString(fragment) {
  return render(fragment);
}
